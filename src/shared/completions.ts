export function codeLanguageCompletions(
	source: string,
	position: number,
	explicit = false,
) {
	let lineStart = source.lastIndexOf("\n", position - 1) + 1
	let match = source
		.slice(lineStart, position)
		.match(/^(`{3,}|~{3,})([\w+-]*)$/)
	if (!match || (!match[2] && !explicit)) return
	let query = (match[2] ?? "").toLowerCase()
	return {
		start: position - query.length,
		end: position,
		options: languages
			.filter(([label]) =>
				query.length === 1 ? label.startsWith(query) : label.includes(query),
			)
			.sort(
				([left], [right]) =>
					relevance(left, query) - relevance(right, query) ||
					left.localeCompare(right),
			),
	}
}

function relevance(label: string, query: string) {
	if (label === query) return 0
	if (label.startsWith(query)) return 1
	return 2
}

